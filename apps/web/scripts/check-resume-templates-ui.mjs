import assert from "node:assert/strict";
import { once } from "node:events";
import { existsSync, mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createServer } from "vite";
import { createOfferFlowServer } from "../../api/src/server.ts";
import { MemoryStore } from "../../api/src/store/memory-store.ts";
import { loadApiConfig } from "../../api/src/config.ts";
import { createEmptyPersonalProfile } from "../../../packages/domain/src/index.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const runtime = join(homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs");
const { chromium } = await import("playwright").catch(() => import(pathToFileURL(runtime).href));
const executablePath = [process.env.CHROME_PATH, "C:/Program Files/Google/Chrome/Application/chrome.exe", "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"].find(p => p && existsSync(p));
const store = new MemoryStore({ persistence: false });
const config = { ...loadApiConfig({}), host: "127.0.0.1", port: 0, opportunitySourceUrl: undefined, opportunitySeedPath: undefined };
const api = createOfferFlowServer({ config, store });
api.server.listen(0, config.host);
await once(api.server, "listening");
const apiUrl = `http://127.0.0.1:${api.server.address().port}`;
const server = await createServer({ root, configFile: join(root, "vite.config.ts"), define: { "import.meta.env.VITE_API_BASE_URL": JSON.stringify(apiUrl) }, logLevel: "error", server: { host: "127.0.0.1", port: 0 } });
await server.listen();
const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
config.allowedOrigins.push(origin);
const browser = await chromium.launch({ executablePath, headless: true });
try {
  const user = store.createUser("resume-ui@example.invalid", "简历测试", "test-password");
  const token = store.createSession(user.id, "user", new Date(Date.now() + 3600000).toISOString()).accessToken;
  const oldProfile = { ...createEmptyPersonalProfile(), fullName: "原有用户", phone: "13800000000", email: "old@example.invalid" };
  const now = new Date().toISOString();
  await store.syncResumeTemplates(user.id, [{ id: "legacy-template", revision: 0, name: "已有云端简历", profile: oldProfile, origin: "extension", createdAt: now, updatedAt: now }]);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: config.cookieName, value: token, url: origin, httpOnly: true, sameSite: "Lax" }]);
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${origin}/app/resumes`);
  await page.getByRole("heading", { name: "简历模板", exact: true }).waitFor();
  await page.getByText("已有云端简历", { exact: true }).waitFor();
  assert.equal(await page.getByText("历史导入", { exact: false }).count(), 1);
  await page.getByRole("button", { name: "使用示例新建", exact: true }).click();
  await page.getByRole("button", { name: "导出 PDF", exact: true }).waitFor();
  const saved = page.waitForResponse(response => response.url().includes("/v1/resume-templates/") && response.request().method() === "PATCH" && response.status() === 200);
  await page.getByLabel("姓名", { exact: true }).fill("云端新用户");
  await saved;
  await page.reload();
  await page.getByLabel("姓名", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("姓名", { exact: true }).inputValue(), "云端新用户");
  const templates = await store.listResumeTemplates(user.id);
  assert.equal(templates.length, 2);
  assert.equal(templates.find(row => row.id === "legacy-template").profile.fullName, "原有用户");
  assert.equal(templates.find(row => row.id !== "legacy-template").profile.fullName, "云端新用户");
  await page.getByRole("button", { name: "返回简历模板", exact: true }).click();
  await page.getByRole("heading", { name: "简历模板", exact: true }).waitFor();
  await page.waitForFunction(() => document.getAnimations().every(animation => animation.playState !== "running"));
  const report = resolve(root, "../../.tmp/local-profiles-ui");
  mkdirSync(report, { recursive: true });
  await page.screenshot({ path: join(report, "web-templates.png"), fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: authenticated template library, legacy content retained, create, edit, API autosave, reload, account storage; no page errors.");
} finally {
  await browser.close();
  await server.close();
  await new Promise(resolve => api.server.close(resolve));
}
